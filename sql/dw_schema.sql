CREATE SCHEMA IF NOT EXISTS dw;
CREATE TABLE IF NOT EXISTS dw.dim_year (
 year_key integer PRIMARY KEY, decade integer NOT NULL
);
CREATE TABLE IF NOT EXISTS dw.dim_category (
 category_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_name text UNIQUE NOT NULL
);
CREATE TABLE IF NOT EXISTS dw.dim_artist (
 artist_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 artist_name text UNIQUE NOT NULL
);
CREATE TABLE IF NOT EXISTS dw.dim_track (
 track_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 track_id text UNIQUE NOT NULL, track_name text NOT NULL, spotify_artists text NOT NULL
);
CREATE TABLE IF NOT EXISTS dw.fact_grammy_record (
 source_row_id bigint PRIMARY KEY,
 year_key integer NOT NULL REFERENCES dw.dim_year,
 category_key bigint NOT NULL REFERENCES dw.dim_category,
 artist_key bigint NOT NULL REFERENCES dw.dim_artist,
 track_key bigint REFERENCES dw.dim_track,
 nominee text,
 eligible boolean NOT NULL,
 match_status text NOT NULL CHECK (match_status IN ('matched','unmatched','ambiguous','missing_key','out_of_scope')),
 candidate_count integer NOT NULL CHECK (candidate_count >= 0),
 popularity double precision CHECK (popularity BETWEEN 0 AND 100),
 energy double precision CHECK (energy BETWEEN 0 AND 1),
 danceability double precision CHECK (danceability BETWEEN 0 AND 1),
 CHECK ((match_status='matched' AND track_key IS NOT NULL AND candidate_count=1 AND popularity IS NOT NULL AND energy IS NOT NULL AND danceability IS NOT NULL)
     OR (match_status<>'matched' AND track_key IS NULL AND popularity IS NULL AND energy IS NULL AND danceability IS NULL))
);
CREATE TABLE IF NOT EXISTS dw.load_audit (
 run_id text PRIMARY KEY, loaded_at timestamptz NOT NULL DEFAULT now(),
 source_rows integer NOT NULL, matched_rows integer NOT NULL, prepared_sha256 text NOT NULL
);
CREATE OR REPLACE VIEW dw.kpi_coverage AS
 SELECT c.category_name, count(*) AS eligible_records,
 count(*) FILTER (WHERE f.match_status='matched') AS matched_records,
 round(100.0*count(*) FILTER (WHERE f.match_status='matched')/NULLIF(count(*),0),2) AS coverage_pct
 FROM dw.fact_grammy_record f JOIN dw.dim_category c USING(category_key)
 WHERE f.eligible GROUP BY c.category_name;
CREATE OR REPLACE VIEW dw.kpi_popularity AS
 SELECT category_name, count(*) AS distinct_tracks, round(avg(popularity)::numeric,2) AS mean_popularity
 FROM (SELECT DISTINCT c.category_name,t.track_id,f.popularity FROM dw.fact_grammy_record f
 JOIN dw.dim_category c USING(category_key) JOIN dw.dim_track t USING(track_key)
 WHERE f.match_status='matched') q GROUP BY category_name;
CREATE OR REPLACE VIEW dw.kpi_audio AS
 SELECT decade, count(*) AS distinct_tracks, round(avg(energy)::numeric,4) AS mean_energy,
 round(avg(danceability)::numeric,4) AS mean_danceability
 FROM (SELECT DISTINCT y.decade,t.track_id,f.energy,f.danceability FROM dw.fact_grammy_record f
 JOIN dw.dim_year y USING(year_key) JOIN dw.dim_track t USING(track_key)
 WHERE f.match_status='matched') q GROUP BY decade;
